s = "python is very easy and it is oop language"
print(s)
print(s.capitalize()) # Python is very easy and it is oop language
print(s.title()) # Python Is Very Easy And It Is Oop Language
print(s.upper()) # PYTHON IS VERY EASY AND IT IS OOP LANGUAGE

s = "HYDERABAD"
print(s.lower()) # hyderabad

print(s.isupper()) # True 
print(s.islower()) # False 

